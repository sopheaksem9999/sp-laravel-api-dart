import 'dart:convert';

/// Field metadata for generated Dart classes.
class _FieldMeta {
  final String jsonKey;
  final String name;
  final String rawType;
  final bool isNullable;

  const _FieldMeta({
    required this.jsonKey,
    required this.name,
    required this.rawType,
    required this.isNullable,
  });

  String get typeSignature => isNullable ? '$rawType?' : rawType;
}

/// Generates immutable Dart data models and table definitions from an OpenAPI specification.
class OpenApiGenerator {
  /// Parsed OpenAPI specification map.
  final Map<String, dynamic> openApi;

  /// Creates an [OpenApiGenerator] for [openApi].
  OpenApiGenerator({required this.openApi});

  /// Factory loading from an OpenAPI JSON string.
  factory OpenApiGenerator.fromJsonString(String jsonStr) {
    return OpenApiGenerator(
      openApi: jsonDecode(jsonStr) as Map<String, dynamic>,
    );
  }

  /// Generates Dart source code representing the schemas and table registry.
  String generate() {
    final buffer = StringBuffer();

    buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
    buffer.writeln('// Generated by sp_laravel_api typegen');
    buffer.writeln();
    buffer.writeln("import 'package:meta/meta.dart';");
    buffer.writeln();

    _generateTablesRegistry(buffer);
    _generateSchemas(buffer);

    return buffer.toString();
  }

  void _generateTablesRegistry(StringBuffer buffer) {
    final paths = openApi['paths'] as Map<String, dynamic>? ?? {};
    final tables = <String>{};

    for (final path in paths.keys) {
      final clean = path.replaceAll(RegExp(r'^/api/v\d+/'), '');
      final segments = clean.split('/');
      if (segments.isNotEmpty) {
        final table = segments.first;
        if (table.isNotEmpty && !table.startsWith('{') && table != 'rpc') {
          tables.add(table);
        }
      }
    }

    if (tables.isEmpty) return;

    buffer.writeln('/// Registry of available database table names.');
    buffer.writeln('class Tables {');
    for (final table in tables) {
      final constName = _toCamelCase(table);
      buffer.writeln("  static const String $constName = '$table';");
    }
    buffer.writeln('}');
    buffer.writeln();
  }

  void _generateSchemas(StringBuffer buffer) {
    final components = openApi['components'] as Map<String, dynamic>? ?? {};
    final schemas = components['schemas'] as Map<String, dynamic>? ?? {};

    for (final entry in schemas.entries) {
      final rawName = entry.key;
      final schema = entry.value as Map<String, dynamic>;

      if (schema['type'] != 'object') continue;

      final className = _toPascalCase(rawName);
      _generateModelClass(buffer, className, schema);
    }
  }

  void _generateModelClass(
    StringBuffer buffer,
    String className,
    Map<String, dynamic> schema,
  ) {
    final properties = schema['properties'] as Map<String, dynamic>? ?? {};
    final requiredSet = Set<String>.from(
      (schema['required'] as List<dynamic>?)?.map((e) => e.toString()) ?? [],
    );

    final fields = <_FieldMeta>[];
    for (final entry in properties.entries) {
      final jsonKey = entry.key;
      final propMap = entry.value as Map<String, dynamic>;
      final isRequired = requiredSet.contains(jsonKey);
      final isNullable = !isRequired || (propMap['nullable'] == true);

      final rawType = _mapDartType(propMap);
      final fieldName = _toCamelCase(jsonKey);

      fields.add(
        _FieldMeta(
          jsonKey: jsonKey,
          name: fieldName,
          rawType: rawType,
          isNullable: isNullable,
        ),
      );
    }

    final desc = schema['description']?.toString() ?? 'Model for $className';
    buffer.writeln('/// $desc');
    buffer.writeln('@immutable');
    buffer.writeln('class $className {');

    // Field declarations
    for (final f in fields) {
      buffer.writeln('  final ${f.typeSignature} ${f.name};');
    }
    buffer.writeln();

    // Constructor
    buffer.writeln('  const $className({');
    for (final f in fields) {
      if (f.isNullable) {
        buffer.writeln('    this.${f.name},');
      } else {
        buffer.writeln('    required this.${f.name},');
      }
    }
    buffer.writeln('  });');
    buffer.writeln();

    // fromJson
    buffer.writeln(
      '  factory $className.fromJson(Map<String, dynamic> json) => $className(',
    );
    for (final f in fields) {
      final parser = _generateFromJsonParser(f);
      buffer.writeln('    ${f.name}: $parser,');
    }
    buffer.writeln('  );');
    buffer.writeln();

    // toJson
    buffer.writeln('  Map<String, dynamic> toJson() => <String, dynamic>{');
    for (final f in fields) {
      buffer.writeln("    '${f.jsonKey}': ${f.name},");
    }
    buffer.writeln('  };');
    buffer.writeln();

    // operator ==
    buffer.writeln('  @override');
    buffer.writeln('  bool operator ==(Object other) =>');
    buffer.writeln('      identical(this, other) ||');
    buffer.writeln('      other is $className &&');
    buffer.writeln('          runtimeType == other.runtimeType');
    for (final f in fields) {
      buffer.writeln('          && ${f.name} == other.${f.name}');
    }
    buffer.writeln('  ;');
    buffer.writeln();

    // hashCode
    buffer.writeln('  @override');
    if (fields.isEmpty) {
      buffer.writeln('  int get hashCode => 0;');
    } else if (fields.length <= 20) {
      final fieldNames = fields.map((f) => f.name).join(', ');
      buffer.writeln('  int get hashCode => Object.hash($fieldNames);');
    } else {
      final fieldNames = fields.map((f) => f.name).join(', ');
      buffer.writeln('  int get hashCode => Object.hashAll([$fieldNames]);');
    }

    buffer.writeln('}');
    buffer.writeln();
  }

  String _generateFromJsonParser(_FieldMeta f) {
    final key = f.jsonKey;
    switch (f.rawType) {
      case 'int':
        if (f.isNullable) {
          return "json['$key'] != null ? (json['$key'] as num).toInt() : null";
        }
        return "(json['$key'] as num).toInt()";

      case 'num':
        if (f.isNullable) {
          return "json['$key'] as num?";
        }
        return "json['$key'] as num";

      case 'bool':
        if (f.isNullable) {
          return "json['$key'] as bool?";
        }
        return "json['$key'] as bool";

      case 'String':
        if (f.isNullable) {
          return "json['$key']?.toString()";
        }
        return "json['$key'].toString()";

      case 'Map<String, dynamic>':
        if (f.isNullable) {
          return "json['$key'] != null ? Map<String, dynamic>.from(json['$key'] as Map) : null";
        }
        return "Map<String, dynamic>.from(json['$key'] as Map)";

      default:
        return "json['$key']";
    }
  }

  String _mapDartType(Map<String, dynamic> prop) {
    final type = prop['type']?.toString();
    switch (type) {
      case 'integer':
        return 'int';
      case 'number':
        return 'num';
      case 'boolean':
        return 'bool';
      case 'string':
        return 'String';
      case 'object':
        return 'Map<String, dynamic>';
      case 'array':
        return 'List<dynamic>';
      default:
        return 'dynamic';
    }
  }

  String _toPascalCase(String input) {
    return input
        .split(RegExp(r'[^a-zA-Z0-9]+'))
        .where((s) => s.isNotEmpty)
        .map((s) => s[0].toUpperCase() + s.substring(1))
        .join('');
  }

  String _toCamelCase(String input) {
    final pascal = _toPascalCase(input);
    if (pascal.isEmpty) return pascal;
    return pascal[0].toLowerCase() + pascal.substring(1);
  }
}
